READING_UNITS = {" Гц": " Hz", " Вт": " W", " дБм": " dBm", " дБ от S9": " dB relative to S9"}


class Message(str):
    """A formatted message that can be rendered after the language changes."""

    def __new__(cls, source, **fields):
        value = super().__new__(cls, source.format(**fields))
        value.source = source
        value.fields = fields
        return value


def translate(value, language):
    if language != "en":
        return str(value)
    if isinstance(value, Message):
        pattern = ENGLISH.get(value.source, value.source)
        fields = {key: translate(field, language) if isinstance(field, Message) else field
                  for key, field in value.fields.items()}
        return pattern.format(**fields)
    return ENGLISH.get(str(value), str(value))


def error_text(error):
    return error.args[0] if error.args and isinstance(error.args[0], Message) else str(error)


def reading_text(value, language):
    rendered = translate(value, language)
    if language == "en":
        for suffix, replacement in READING_UNITS.items():
            if rendered.endswith(suffix):
                return rendered.removesuffix(suffix) + replacement
    return rendered
